import json

with open('dataset.json', 'r', encoding='utf-8') as f:
    data = json.load(f)

lines = []
lines.append('--[[')
lines.append('    CasePool.luau')
lines.append('    Koleksi 41 Kasus Medis Pre-test (Stratified Pool)')
lines.append('    - abses_periapikal: 19 kasus (case_001 s.d. case_019 | ABS-01 s.d. ABS-19)')
lines.append('    - granuloma_periapikal: 8 kasus (case_026 s.d. case_033 | GRN-01 s.d. GRN-08)')
lines.append('    - kista_radikuler: 14 kasus (case_051 s.d. case_064 | KIS-01 s.d. KIS-14)')
lines.append('--]]')
lines.append('')
lines.append('local CasePool = {}')
lines.append('CasePool.Cases = {}')
lines.append('CasePool.ByCategory = {')
lines.append('    abses_periapikal = {},')
lines.append('    granuloma_periapikal = {},')
lines.append('    kista_radikuler = {}')
lines.append('}')
lines.append('')
lines.append('local function add(id, kode, kat, diag, elemen, vignette, radId, intraId)')
lines.append('    local item = {')
lines.append('        id = id,')
lines.append('        kode_kasus = kode,')
lines.append('        kategori_lesi = kat,')
lines.append('        diagnosis_benar = diag,')
lines.append('        elemen_gigi = elemen,')
lines.append('        vignette_tes = vignette,')
lines.append('        radiograf_asset_id = radId or "",')
lines.append('        intraoral_asset_id = intraId or ""')
lines.append('    }')
lines.append('    table.insert(CasePool.Cases, item)')
lines.append('    if CasePool.ByCategory[kat] then')
lines.append('        table.insert(CasePool.ByCategory[kat], item)')
lines.append('    end')
lines.append('end')
lines.append('')

for c in data:
    cid = c['id']
    kode = c['kode_kasus']
    kat = c['kategori_lesi']
    diag = c['diagnosis_benar']
    elemen = c.get('elemen_gigi', '')
    vignette = c['vignette_tes'].replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
    lines.append(f'add("{cid}", "{kode}", "{kat}", "{diag}", "{elemen}", "{vignette}", "", "")')

lines.append('')
lines.append('-- =========================================================================')
lines.append('-- LOGIKA STRATIFIED RANDOM SAMPLING (3 Abses, 3 Granuloma, 3 Kista)')
lines.append('-- =========================================================================')
lines.append('function CasePool.Shuffle(tbl)')
lines.append('    local cloned = table.clone(tbl)')
lines.append('    local n = #cloned')
lines.append('    for i = n, 2, -1 do')
lines.append('        local j = math.random(1, i)')
lines.append('        cloned[i], cloned[j] = cloned[j], cloned[i]')
lines.append('    end')
lines.append('    return cloned')
lines.append('end')
lines.append('')
lines.append('function CasePool.SampleWithoutReplacement(tbl, count)')
lines.append('    local shuffled = CasePool.Shuffle(tbl)')
lines.append('    local res = {}')
lines.append('    for i = 1, math.min(count, #shuffled) do')
lines.append('        table.insert(res, shuffled[i])')
lines.append('    end')
lines.append('    return res')
lines.append('end')
lines.append('')
lines.append('function CasePool.GenerateStratifiedPretest(excludeIds)')
lines.append('    excludeIds = excludeIds or {}')
lines.append('    local excludeMap = {}')
lines.append('    for _, id in ipairs(excludeIds) do excludeMap[id] = true end')
lines.append('')
lines.append('    local function getAvailable(category)')
lines.append('        local list = CasePool.ByCategory[category] or {}')
lines.append('        local available = {}')
lines.append('        for _, c in ipairs(list) do')
lines.append('            if not excludeMap[c.id] then')
lines.append('                table.insert(available, c)')
lines.append('            end')
lines.append('        end')
lines.append('        if #available < 3 then return list end')
lines.append('        return available')
lines.append('    end')
lines.append('')
lines.append('    local selAbses = CasePool.SampleWithoutReplacement(getAvailable("abses_periapikal"), 3)')
lines.append('    local selGranu = CasePool.SampleWithoutReplacement(getAvailable("granuloma_periapikal"), 3)')
lines.append('    local selKista = CasePool.SampleWithoutReplacement(getAvailable("kista_radikuler"), 3)')
lines.append('')
lines.append('    local combined9 = {}')
lines.append('    for _, c in ipairs(selAbses) do table.insert(combined9, c) end')
lines.append('    for _, c in ipairs(selGranu) do table.insert(combined9, c) end')
lines.append('    for _, c in ipairs(selKista) do table.insert(combined9, c) end')
lines.append('')
lines.append('    return CasePool.Shuffle(combined9)')
lines.append('end')
lines.append('')
lines.append('return CasePool')

content = '\n'.join(lines)
with open('CasePool_clean.luau', 'w', encoding='utf-8') as f:
    f.write(content)

print(f"Generated CasePool_clean.luau: {len(lines)} lines, {len(content)} bytes.")

